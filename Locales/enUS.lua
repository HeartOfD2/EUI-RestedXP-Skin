-- Base locale. Keys ARE the English text; missing translations fall back to the key.
local _, ns = ...
local L = setmetatable({}, { __index = function(_, key) return key end })
ns.L = L

-- Language of our texts: the EllesmereUI option "EUI Options Language" (EllesmereUIDB.displayLocale) wins over the
-- game client. Only German is translated; every other language, Spanish included, stays English.
function ns.Locale()
    local override = EllesmereUIDB and EllesmereUIDB.displayLocale
    if type(override) == "string" and override ~= "auto" then return override end
    return GetLocale()
end

